def test_upgrade_downgrade_upgrade_es_reversible(database_url: str) -> None:
    """Cada migración debe poder ir y volver: sin esto, un rollback en
    producción es un viaje sin retorno."""
    config = alembic_config(database_url)
    command.upgrade(config, "head")
    command.downgrade(config, "base")
    command.upgrade(config, "head")

    assert APP_TABLES <= _tables(database_url)


def test_los_datos_sobreviven_a_las_migraciones(database_url: str) -> None:
    """El caso que importa: una base con datos que salta de la primera revisión
    a head sin perder filas, y con el backfill del flag aplicado."""
    config = alembic_config(database_url)
    command.upgrade(config, INITIAL_REVISION)
    _seed_household_and_user(database_url)

    command.upgrade(config, "head")

    assert _scalar(database_url, "SELECT count(*) FROM users") == 2
    assert _scalar(database_url, "SELECT name FROM users WHERE id = 'u1'") == "Ana"
    assert _scalar(database_url, "SELECT count(*) FROM households") == 2
    assert _scalar(database_url, "SELECT count(*) FROM accounts WHERE owner_id IS NOT NULL") == 0
    assert _scalar(database_url, "SELECT owner_id FROM households WHERE id = 'h1'") == "u1"
    assert _scalar(
        database_url, "SELECT owner_id FROM households WHERE id = 'h_orphan'"
    ) is None
    engine = create_engine(database_url)
    try:
        with pytest.raises(IntegrityError):
            with engine.begin() as connection:
                connection.execute(
                    text("UPDATE households SET owner_id = 'u2' WHERE id = 'h_orphan'")
                )
    finally:
        engine.dispose()
    # La migración del onboarding marca a los usuarios que ya existían: si no,
    # verían un wizard que no les toca.
    assert _scalar(
        database_url, "SELECT onboarding_completed_at FROM users WHERE id = 'u1'"
    ) is not None


def test_el_backfill_de_recurrentes_no_deja_reglas_sin_autor(database_url: str) -> None:
    """`created_by_id` es NOT NULL. La tabla nunca fue escribible, así que en la
    práctica está vacía, pero si una base tuviera filas el backfill tiene que
    resolverlas al miembro más antiguo del hogar en vez de tumbar el arranque."""
    config = alembic_config(database_url)
    command.upgrade(config, "673ed5f3d911")
    _seed_household_and_user(database_url)
    _seed_recurring_rule(database_url)

    command.upgrade(config, "head")

    assert _scalar(database_url, "SELECT count(*) FROM recurring_rules") == 1
    assert _scalar(database_url, "SELECT created_by_id FROM recurring_rules") == "u1"
    # anchor_day queda NULL: la regla vieja no declaraba día ancla y el avance
    # cae en el día de next_run_date.
    assert _scalar(database_url, "SELECT anchor_day FROM recurring_rules") is None


def test_puente_pre_alembic_no_recrea_ni_borra_nada(database_url: str) -> None:
    """Simula el despliegue real que existía antes de Alembic: esquema en la
    revisión inicial, con datos, y sin `alembic_version`. El bootstrap debe
    stampear y seguir migrando, no re-crear tablas."""
    command.upgrade(alembic_config(database_url), INITIAL_REVISION)
    _seed_household_and_user(database_url)

    engine = create_engine(database_url)
    try:
        with engine.begin() as connection:
            connection.execute(text("DROP TABLE alembic_version"))
    finally:
        engine.dispose()
    assert db_bootstrap._is_pre_alembic_database(database_url)

    db_bootstrap.main(database_url)

    assert _scalar(database_url, "SELECT version_num FROM alembic_version") == _head_revision()
    # Los datos siguen ahí → no re-creó las tablas
    assert _scalar(database_url, "SELECT name FROM users WHERE id = 'u1'") == "Ana"
    assert _scalar(
        database_url, "SELECT onboarding_completed_at FROM users WHERE id = 'u1'"
    ) is not None


def test_bootstrap_es_idempotente(database_url: str) -> None:
    """Cada arranque del contenedor lo ejecuta: correrlo dos veces no debe
    fallar ni mover nada."""
    db_bootstrap.main(database_url)
    first = _scalar(database_url, "SELECT onboarding_completed_at FROM users LIMIT 1")

    db_bootstrap.main(database_url)

    assert _scalar(database_url, "SELECT version_num FROM alembic_version") == _head_revision()
    assert _scalar(database_url, "SELECT onboarding_completed_at FROM users LIMIT 1") == first


