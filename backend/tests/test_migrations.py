"""Tests de migraciones contra Postgres real.

Los demás tests corren sobre SQLite en memoria con `create_all`, que no prueba
nada de Alembic. Estos sí: verifican que una migración no rompa una base con
datos, que el esquema migrado coincida con los modelos y que el puente para
bases pre-Alembic no re-cree tablas.

Necesitan un servidor Postgres. Se activan con:

    MIGRATIONS_TEST_DATABASE_URL=postgresql+psycopg://budget:budget@localhost:5432/postgres \\
        uv run pytest tests/test_migrations.py

Sin esa variable se saltan (así `uv run pytest` sigue siendo offline y rápido).
En CI la provee el servicio `db` del workflow. Cada test corre contra una base
recién creada y la borra al terminar: nunca tocan la base apuntada por la URL.
"""

import os
import threading
from collections.abc import Iterator

import pytest
from sqlalchemy import create_engine, inspect, text
from sqlalchemy.exc import IntegrityError

from alembic import command
from alembic.script import ScriptDirectory
from alembic.util.exc import AutogenerateDiffsDetected
from app import db_bootstrap
from app.db_bootstrap import INITIAL_REVISION, alembic_config

ADMIN_URL = os.environ.get("MIGRATIONS_TEST_DATABASE_URL")

# En CI, saltarse estos tests sería un falso verde: el job los pide con
# MIGRATIONS_TEST_REQUIRED=1 y sin base preferimos que reviente al recolectar.
if not ADMIN_URL and os.environ.get("MIGRATIONS_TEST_REQUIRED") == "1":
    raise RuntimeError(
        "MIGRATIONS_TEST_REQUIRED=1 pero falta MIGRATIONS_TEST_DATABASE_URL: "
        "el servicio de Postgres no llegó."
    )

pytestmark = pytest.mark.skipif(
    not ADMIN_URL,
    reason="requiere MIGRATIONS_TEST_DATABASE_URL apuntando a un Postgres",
)

#: Tablas de la aplicación, sin contar `alembic_version`.
