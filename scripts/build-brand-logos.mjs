/**
 * Compiles the SVGs under frontend/public/brands/ into a single TS module
 * (frontend/src/lib/brand-logos.generated.ts) so the app can look up every
 * mark by slug.
 *
 * Two kinds of source files:
 * - Simple Icons style: single <path>, viewBox 0 0 24 24, no gradients. These
 *   compile to a `{ kind: "path", d, color }` entry, drawn inline and tinted
 *   with currentColor (BrandMedallion).
 * - Anything else (official press-kit SVGs, Wikimedia marks, multi-color,
 *   multi-path, native viewBox): compiles to a `{ kind: "image", path }`
 *   entry referencing the static file under /brands/ and rendered as an
 *   <img>, in its own original colors/proportions.
 *
 * If you add a logo, drop the .svg in the right folder and re-run this script.
 *
 *   node scripts/build-brand-logos.mjs
 */
import { readdirSync, readFileSync, writeFileSync, mkdirSync, statSync } from "node:fs"
import { join, dirname, resolve, relative, sep } from "node:path"
import { fileURLToPath } from "node:url"

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..")
const brandsDir = join(root, "frontend", "public", "brands")
const outFile = join(root, "frontend", "src", "lib", "brand-logos.generated.ts")

function collectSvgs(dir, acc = []) {
  for (const entry of readdirSync(dir)) {
    const p = join(dir, entry)
    if (statSync(p).isDirectory()) collectSvgs(p, acc)
    else if (entry.endsWith(".svg")) acc.push(p)
  }
  return acc
}

const logos = {}
let skipped = []

for (const file of collectSvgs(brandsDir)) {
  const raw = readFileSync(file, "utf8")
  const slug = file.split(/[\\/]/).pop().replace(/\.svg$/, "")
  if (!raw.includes("<svg")) {
    skipped.push(`${slug}: not an SVG`)
    continue
  }
  const title = (raw.match(/<title>([^<]*)<\/title>/) ?? [])[1] ?? slug
  const paths = [...raw.matchAll(/<path[^>]*\bd="([^"]+)"/g)].map((m) => m[1])
  if (!paths.length) {
    skipped.push(`${slug}: no <path>`)
    continue
  }

  const viewBox = ((raw.match(/<svg[^>]*\bviewBox="([^"]+)"/) ?? [])[1] ?? "")
    .trim()
    .replace(/\s+/g, " ")
  const hasGradient = /url\(#|<(linearGradient|radialGradient)/.test(raw)
  const conforming = paths.length === 1 && viewBox === "0 0 24 24" && !hasGradient

  if (conforming) {
    const fill = (raw.match(/<svg[^>]*\bfill="([^"]+)"/) ?? [])[1] ?? "#0f172a"
    logos[slug] = { kind: "path", title, color: fill.toLowerCase(), d: paths[0] }
  } else {
    const relPath = relative(brandsDir, file).split(sep).join("/")
    logos[slug] = { kind: "image", title, path: relPath }
  }
}

const lines = [
  "// AUTO-GENERATED by scripts/build-brand-logos.mjs — DO NOT EDIT.",
  "// Re-run after adding or removing SVGs under frontend/public/brands/.",
  "",
  "export type BrandLogo =",
  "  | {",
  "      kind: \"path\"",
  "      /** Brand name, from the <title> of the source SVG. */",
  "      title: string",
  "      /** Brand color from the SVG fill (used for the medallion tint). */",
  "      color: string",
  "      /** Single path data (Simple Icons style), viewBox 0 0 24 24. */",
  "      d: string",
  "    }",
  "  | {",
  "      kind: \"image\"",
  "      /** Brand name, from the <title> of the source SVG. */",
  "      title: string",
  "      /** Path relative to /brands/, e.g. \"banks/bbva.svg\". */",
  "      path: string",
  "    }",
  "",
  "export const BRAND_LOGOS: Record<string, BrandLogo> = {",
]
for (const slug of Object.keys(logos).sort()) {
  lines.push(`  ${JSON.stringify(slug)}: ${JSON.stringify(logos[slug])},`)
}
lines.push("}", "")

mkdirSync(dirname(outFile), { recursive: true })
writeFileSync(outFile, lines.join("\n"))

console.log(`wrote ${Object.keys(logos).length} logos -> ${outFile}`)
if (skipped.length) {
  console.warn("skipped:")
  for (const s of skipped) console.warn(`  - ${s}`)
}
